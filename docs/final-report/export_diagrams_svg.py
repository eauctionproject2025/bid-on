def main():
    SVG.mkdir(parents=True, exist_ok=True)
    PNG_NOTE.mkdir(parents=True, exist_ok=True)
    readme = PNG_NOTE / "README.md"
    readme.write_text(
        "PNG raster exports require Mermaid CLI with a working Chrome/Puppeteer.\n"
        "SVG academic fallbacks were generated by export_diagrams_svg.py.\n"
        "Open `.mmd` / `.puml` / `.drawio` sources for full graphical editing.\n",
        encoding="utf-8",
    )
    for name, (title, lines) in DIAGRAMS.items():
        path = SVG / f"{name}.svg"
        path.write_text(svg_for(title, lines), encoding="utf-8")
        print("Wrote", path)
    # also copy note next to plantuml sources reminder
    (SVG / "README.md").write_text(
        "SVG fallbacks summarize diagram content for archival when Puppeteer cannot launch.\n"
        "Prefer rendering docs/diagrams/source/* in Mermaid Live Editor or diagrams.net.\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
