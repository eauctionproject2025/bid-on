# -*- coding: utf-8 -*-
"""Create simple academic SVG exports from diagram titles (Puppeteer-free fallback)."""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "diagrams"
SRC = ROOT / "source"
SVG = ROOT / "exports" / "svg"
PNG_NOTE = ROOT / "exports" / "png"


def svg_for(title: str, lines: list[str]) -> str:
    height = 80 + 22 * len(lines)
    body = "\n".join(
        f'<text x="40" y="{70 + i * 22}" font-family="Times New Roman, serif" font-size="14">{_esc(line)}</text>'
        for i, line in enumerate(lines)
    )
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="900" height="{height}" viewBox="0 0 900 {height}">
  <rect width="100%" height="100%" fill="#ffffff"/>
  <rect x="16" y="16" width="868" height="{height - 32}" fill="none" stroke="#222" stroke-width="2"/>
  <text x="40" y="48" font-family="Times New Roman, serif" font-size="18" font-weight="bold">{_esc(title)}</text>
  {body}
  <text x="40" y="{height - 24}" font-family="Times New Roman, serif" font-size="11" fill="#555">Source: editable .mmd/.puml under docs/diagrams/source — open in Mermaid Live / PlantUML / diagrams.net for graphical rendering.</text>
</svg>
'''


def _esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


